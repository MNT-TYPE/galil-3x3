def build():
    teams = {tid: {"name": name, "categoryId": cat, "players": players, "order": i}
             for i, (tid, cat, name, players) in enumerate(TEAMS)}
    houses = {hid: {"name": name, "categoryId": cat, "teamIds": tids, "order": i}
              for i, (hid, cat, name, tids) in enumerate(HOUSES)}
    games = {}
    n = 0
    for cat, house, time, court, a, b in HOUSE_GAMES:
        n += 1
        games[f"g{n:03d}"] = {"categoryId": cat, "houseId": house, "stage": "house",
                              "time": time, "court": court, "teamA": a, "teamB": b,
                              "labelA": "", "labelB": "", "scoreA": None, "scoreB": None, "order": n}
    for cat, stage, time, court, la, lb in PLAYOFF_GAMES:
        n += 1
        games[f"g{n:03d}"] = {"categoryId": cat, "houseId": "", "stage": stage,
                              "time": time, "court": court, "teamA": "", "teamB": "",
                              "labelA": la, "labelB": lb, "scoreA": None, "scoreB": None, "order": n}
    return {
        "settings": {
            "name": "אליפות הגליל בכדורסל 3X3 לזכר הבנים",
            "year": "2026",
            "date": "",
            "location": "",
            "shareUrl": "https://claude.ai/artifact/P4xMcWLZwLUr4Vccogf4WX",
            "courts": COURTS,
            "categories": CATEGORIES,
        },
        "teams": teams,
        "houses": houses,
        "games": games,
    }

if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "seed.json")
    data = build()
